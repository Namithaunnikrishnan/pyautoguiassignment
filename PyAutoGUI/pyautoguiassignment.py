import pyautogui
import time
from datetime import datetime
pyautogui.FAILSAFE = True
pyautogui.PAUSE = 1.0

print("Open the browser..")
time.sleep(1)
pyautogui.hotkey('win', 'r')
time.sleep(1)
pyautogui.write('chrome',interval=0.1)
time.sleep(1)
pyautogui.press('Enter')
time.sleep(1)
print("opening the website...")
pyautogui.hotkey('ctrl', 't')
time.sleep(1)
pyautogui.write('https://www.accuweather.com/en/in/kochi/204289/weather-forecast/204289',interval=0.1)
time.sleep(1)
pyautogui.press('Enter')
time.sleep(5)

print("copying the data... ")
pyautogui.click(291, 956, duration=1)
time.sleep(3)
pyautogui.moveTo(1040, 990, duration=1)
pyautogui.dragTo(1089, 1006, duration=1)
pyautogui.hotkey('ctrl', 'c')
time.sleep(1)
print("data copied successfully..")
print("opening the excel sheet...")
pyautogui.hotkey('win', 'r')
time.sleep(1)
pyautogui.write('excel',interval=0.1)
time.sleep(1)
pyautogui.press('Enter')
time.sleep(5)
pyautogui.click(280, 280)
time.sleep(5)
print("CREATING THE HEADERS")
pyautogui.write('Date&Time',interval=0.1)
pyautogui.press('tab')
pyautogui.write('fetched data',interval=0.1)
pyautogui.press('tab')
pyautogui.write('comment',interval=0.1)
pyautogui.press('tab')
pyautogui.hotkey('ctrl', 'home')
pyautogui.press('down')
time.sleep(1)
currenttime=datetime.now().strftime("%d/%m/%Y %H:%M:%S")
pyautogui.write(currenttime,interval=0.1)
pyautogui.press('tab')
pyautogui.hotkey('ctrl', 'v')
pyautogui.press('tab')
pyautogui.write('data fetched successfully',interval=0.1)
print("data pasted successfully..")
